import fs from "node:fs";
import path from "node:path";

const ROOT=process.cwd();
const APP=path.join(ROOT,"src","app","api");
const criticalPrefixes=["/admin/","/billing/","/checkout","/orders","/payments/","/wallet","/escrow","/locker","/automation/","/compliance/","/disputes/","/negotiations/","/b2b/","/developer/","/v1/","/social/","/chat/","/ai/agent","/ai/product-publisher","/commerce-studio/","/risk/","/intelligence/","/inventory/"];
const publicRoutes=new Set(["/health","/catalog","/markets","/agentic/catalog","/v1/openapi","/affiliate","/payments/webhook","/billing/webhook","/payments/coinbase/webhook"]);

function walk(dir,out=[]){
  if(!fs.existsSync(dir)) return out;
  for(const e of fs.readdirSync(dir,{withFileTypes:true})){
    const f=path.join(dir,e.name);
    if(e.isDirectory()) walk(f,out);
    else if(e.name==="route.ts"||e.name==="route.js") out.push(f);
  }
  return out;
}
function routeOf(file){return "/api/"+path.relative(APP,path.dirname(file)).replaceAll("\\","/");}

const rows=[];
for(const file of walk(APP)){
  const body=fs.readFileSync(file,"utf8"), route=routeOf(file);
  const auth=/auth\.getUser\(|requireAuth\(|Authorization|Bearer|api[_-]?key|oauth/i.test(body);
  const role=/role|admin|permission|scope/i.test(body);
  const validation=/zod|safeParse\(|\.parse\(/i.test(body);
  const rate=/rateLimit|distributedRateLimit|consume_api_rate_limit/i.test(body);
  const idem=/idempotency/i.test(body);
  const webhook=/webhook/i.test(body);
  const critical=criticalPrefixes.some(p=>route===p||route.startsWith(p));
  const expectedAuth=critical&&!publicRoutes.has(route)&&!webhook;
  rows.push({route,auth,role,validation,rate,idem,expectedAuth});
}
rows.sort((a,b)=>a.route.localeCompare(b.route));

const lines=["# Credi API Security Matrix","","Generated by `npm run audit:api`. Static analysis is a signal, not proof of runtime authorization.","","| Endpoint | Auth signal | Role/scope signal | Validation | Rate limit | Idempotency | Expected auth |","|---|---:|---:|---:|---:|---:|---:|"];
for(const row of rows){
  lines.push("| `"+row.route+"` | "+(row.auth?"✓":"—")+" | "+(row.role?"✓":"—")+" | "+(row.validation?"✓":"—")+" | "+(row.rate?"✓":"—")+" | "+(row.idem?"✓":"—")+" | "+(row.expectedAuth?"REQUIRED":"PUBLIC/WEBHOOK")+" |");
}
const docs=path.join(ROOT,"docs","API-SECURITY-MATRIX.md");
fs.mkdirSync(path.dirname(docs),{recursive:true});
fs.writeFileSync(docs,lines.join("\n")+"\n");

const misses=rows.filter(row=>row.expectedAuth&&!row.auth);
console.log("API routes audited:",rows.length);
console.log("Critical routes without an obvious auth signal:",misses.length);
for(const row of misses) console.log("- "+row.route);
if(misses.length) process.exit(1);
console.log("API security static audit: PASSED");
